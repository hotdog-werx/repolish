class TestParamParity:
    def test_lane_subcommands_expose_the_apply_flags(
        self,
        lane_cli: LaneCli,
    ) -> None:
        """Lane params derive from the apply CLI's model, so flags cannot drift."""
        app, _, _ = lane_cli

        result = runner.invoke(app, ['actions', '--help'])

        assert result.exit_code == 0, result.output
        for flag in (
            '--config',
            '--check',
            '--skip-post-process',
            '--fail-on-warnings',
        ):
            assert flag in result.output

    def test_lane_post_process_runs_and_skip_flag_honored(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        # A named lane runs only its own fast_lanes.config post_process
        # commands; the project's top-level post_process never applies.
        provider_cls = _make_provider_pkg(
            tmp_path,
            _LANE_PROVIDER,
            templates=_TEMPLATES,
        )
        app = provider_cli(provider_cls)
        project = _stage_project(
            provider_cls,
            tmp_path,
            extra_config={
                'post_process': ['touch project.txt'],
                'fast_lanes': {
                    'config': {'actions': {'post_process': ['touch lane.txt']}},
                },
            },
        )
        monkeypatch.chdir(project)

        skipped = runner.invoke(app, ['actions', '--skip-post-process'])
        assert skipped.exit_code == 0, skipped.output
        assert not (project / 'lane.txt').exists()

        applied = runner.invoke(app, ['actions'])
        assert applied.exit_code == 0, applied.output
        assert (project / 'lane.txt').exists()
        assert not (project / 'project.txt').exists()  # project commands skipped

    def test_lane_without_config_entry_runs_no_post_process(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        # The point of per-lane config: a lane with no entry runs nothing at
        # all, so a python-only lane never runs the project's dprint.
        provider_cls = _make_provider_pkg(
            tmp_path,
            _LANE_PROVIDER,
            templates=_TEMPLATES,
        )
        app = provider_cli(provider_cls)
        project = _stage_project(
            provider_cls,
            tmp_path,
            extra_config={'post_process': ['touch project.txt']},
        )
        monkeypatch.chdir(project)

        result = runner.invoke(app, ['actions'])

        assert result.exit_code == 0, result.output
        assert not (project / 'project.txt').exists()

    def test_all_subcommand_runs_project_post_process(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        # `all` mirrors a full provider pass: the project's commands apply.
        provider_cls = _make_provider_pkg(
            tmp_path,
            _LANE_PROVIDER,
            templates=_TEMPLATES,
        )
        app = provider_cli(provider_cls)
        project = _stage_project(
            provider_cls,
            tmp_path,
            extra_config={'post_process': ['touch project.txt']},
        )
        monkeypatch.chdir(project)

        result = runner.invoke(app, ['all'])

        assert result.exit_code == 0, result.output
        assert (project / 'project.txt').exists()


