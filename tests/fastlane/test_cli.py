class TestConfigHandling:
    def test_paused_files_from_real_config_are_honored(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        provider_cls = _make_provider_pkg(
            tmp_path,
            _LANE_PROVIDER,
            templates=_TEMPLATES,
        )
        app = provider_cli(provider_cls)
        project = _stage_project(
            provider_cls,
            tmp_path,
            extra_config={'paused_files': ['plain.txt']},
        )
        monkeypatch.chdir(project)

        result = runner.invoke(app, ['actions'])

        assert result.exit_code == 0, result.output
        assert not (project / 'plain.txt').exists()
        assert (project / 'action1' / 'action.yaml').exists()

    def test_check_flag_compares_without_writing(
        self,
        lane_cli: LaneCli,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        app, project, _ = lane_cli
        monkeypatch.chdir(project)

        missing = runner.invoke(app, ['actions', '--check'])
        assert missing.exit_code == 2, missing.output
        assert not (project / 'action1' / 'action.yaml').exists()

        runner.invoke(app, ['actions'])
        clean = runner.invoke(app, ['actions', '--check'])
        assert clean.exit_code == 0, clean.output

    def test_runs_without_config_file(
        self,
        lane_cli: LaneCli,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        # A lane CLI is an extension of the provider package: it works in any
        # directory, registered or not. Without a repolish.yaml the run falls
        # back to the package name as the provider identity.
        app, _, _ = lane_cli
        empty = tmp_path / 'empty-project'
        empty.mkdir()
        monkeypatch.chdir(empty)

        result = runner.invoke(app, ['actions'])

        assert result.exit_code == 0, result.output
        assert (empty / 'action1' / 'action.yaml').read_text(
            encoding='utf-8',
        ) == ('# generated by pkg\nruns: uvx --from action1.main\n')

    def test_unlisted_provider_still_honors_project_keys(
        self,
        tmp_path: Path,
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        provider_cls = _make_provider_pkg(
            tmp_path,
            _LANE_PROVIDER,
            templates=_TEMPLATES,
        )
        app = provider_cli(provider_cls)
        project = tmp_path / 'project'
        project.mkdir()
        # The config registers some other provider; this CLI's package is not
        # listed. The lane still runs, and the project's paused_files apply.
        (project / 'repolish.yaml').write_text(
            yaml.safe_dump(
                {
                    'providers': {
                        'other': {'provider_root': '/definitely/not/this'},
                    },
                    'paused_files': ['plain.txt'],
                },
            ),
            encoding='utf-8',
        )
        monkeypatch.chdir(project)

        result = runner.invoke(app, ['actions'])

        assert result.exit_code == 0, result.output
        assert (project / 'action1' / 'action.yaml').exists()
        assert not (project / 'plain.txt').exists()  # paused_files honored


